package Exercicio_Conta_Bancaria;
public class Operacoes {

    float soma (float n1, float n2){
        return n1 + n2;  }
    float subtracao (float n1, float n2){
        return n1 - n2;  }
    float multiplicacao (float n1, float n2){
        return n1 * n2;  }
    float exponenciacao (float n1){
        return n1 * n1;  }
}
